
import requests
import json

from pathlib import Path
from tools.log_analyzer import analyze_logs, detect_brute_force


MODEL = "llama3"
LOG_FILE = Path("logs/auth.log")

OLLAMA_URL = "http://localhost:11434/api/generate"


SYSTEM_PROMPT = """
You are Northstar SOC Agent, a cybersecurity investigation assistant.

Your responsibilities:
1. Analyse authentication activity.
2. Identify suspicious source IP addresses.
3. Identify targeted user accounts.
4. Explain detection alerts.
5. Assess potential security impact.
6. Recommend investigation steps.

STRICT RULES:
- Use only the supplied evidence.
- Never invent events, dates or timestamps.
- Do not assume an account was compromised without evidence.
- Do not assume failed logins caused account lockouts.
- Do not claim data theft without evidence.
- Do not invent confidence percentages.
- Separate confirmed observations from suspicions.
- Python-generated detection results are authoritative for event counts.
- Keep the report concise.
"""


def read_logs():
    """Read authentication logs."""

    if not LOG_FILE.exists():
        raise FileNotFoundError(
            f"Log file not found: {LOG_FILE}"
        )

    return LOG_FILE.read_text(encoding="utf-8")


def investigate(log_data, evidence, alerts):
    """Send evidence and detection alerts to local Llama 3."""

    prompt = f"""
{SYSTEM_PROMPT}

RAW AUTHENTICATION LOGS:

{log_data}

STRUCTURED EVIDENCE EXTRACTED BY PYTHON:

{json.dumps(evidence, indent=2)}

DETECTION ALERTS GENERATED BY PYTHON:

{json.dumps(alerts, indent=2)}

Prepare your investigation report using these headings:

1. Observed Activity
2. Suspicious Indicators
3. Potential Impact
4. Recommended Next Steps
5. Confidence and Evidence Limitations
6. Detection Alert Analysis

Explain the detection alerts using the supplied evidence.

Do not invent information that is absent from the logs.
"""

    response = requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL,
            "prompt": prompt,
            "stream": False,
            "options": {
                "num_predict": 800
            }
        },
        timeout=(10, 600)
    )

    response.raise_for_status()

    return response.json()["response"]


def save_report(findings):
    """Save investigation report."""

    output_dir = Path("output")
    output_dir.mkdir(exist_ok=True)

    report_file = output_dir / "investigation-report.txt"

    report_file.write_text(
        findings,
        encoding="utf-8"
    )

    return report_file


def main():

    print("\nNORTHSTAR SOC AGENT")
    print("=" * 40)

    try:
        logs = read_logs()

        print("[+] Raw logs loaded")

        evidence = analyze_logs()

        print("[+] Structured evidence extracted")

        alerts = detect_brute_force(evidence)

        print(f"[+] Detection alerts generated: {len(alerts)}")

        print("[+] Sending evidence to local AI model...\n")

        findings = investigate(
            logs,
            evidence,
            alerts
        )

        print("\nINVESTIGATION REPORT")
        print("=" * 40)

        print(findings)

        report_file = save_report(findings)

        print(f"\n[+] Report saved to {report_file}")

    except requests.exceptions.Timeout:
        print("[!] Ollama request timed out.")

    except requests.exceptions.ConnectionError:
        print("[!] Cannot connect to Ollama. Check that Ollama is running.")

    except Exception as error:
        print(f"[!] Error: {error}")


if __name__ == "__main__":
    main()

